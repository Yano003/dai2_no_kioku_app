/// アプリの表示名とブランドタグライン。
///
/// ■ アプリ名は確定済み（2026年8月7日 木須様よりご決定）
/// 名称：キオクヲ／タグライン：思い出せる安心が、自信になる。
///
/// 「オ」と「ヲ」の語呂で覚えやすく、助詞「を」で終わることで余白が生まれ、
/// 「キオクヲひらく」「キオクヲ明日へ」のように展開できる、という意図。
/// この余白を潰さないよう、名称の後ろに語を足した表記（「キオクヲアプリ」等）は
/// UI では使わないこと。
///
/// ■ 表示名を変更するときに触る3箇所
/// Dart から OS のアプリ一覧に出る名前を設定することはできないため、
/// ネイティブの設定ファイルにも同じ文字列を書く必要がある。
/// 変更手順は README の「アプリ名を変更する手順」に記載している。
///
///   1. このファイルの [AppIdentity.displayName]
///   2. android/app/src/main/res/values/strings.xml の app_name
///   3. ios/Runner/Info.plist の CFBundleDisplayName
///
/// ■ パッケージ名（アプリケーション ID）は別物
/// jp.co.hitokoto.kiokuwo はストア公開後に変更できない。
/// 表示名の変更に引きずられて変えないこと。
library;

class AppIdentity {
  const AppIdentity._();

  /// アプリの表示名。ストア表記・アプリ一覧・画面内の表記すべてで使う。
  static const displayName = 'キオクヲ';

  /// ブランドタグライン。（2026年8月7日 木須様よりご提供）
  ///
  /// 事業コンセプト「あなたの自信を支える、もう1つの記憶。」を、
  /// 利用者に向けた一文に言い換えたもの。
  static const tagline = '思い出せる安心が、自信になる。';
}
