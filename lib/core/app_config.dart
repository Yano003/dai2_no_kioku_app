/// 未確定仕様の既定値を集約したファイル。
///
/// 要件定義書 第1.0版 11章「確認事項」および、レビューで追加提起した項目の
/// 暫定回答をここに集約する。発注者からの回答が確定したら、原則として
/// このファイルの値を変更するだけで挙動が切り替わるようにしている。
///
/// 各定数には対応する確認事項番号を付記する。
library;

import 'clock_time.dart';

/// 繰り返し予定の種別。
enum RepeatType {
  /// 繰り返さない単発の予定。
  none,

  /// 毎日（毎朝・毎晩を含む）。
  daily,

  /// 毎週指定曜日。
  weekly,
}

/// 未完了予定の翌日以降の扱い。（確認事項 No.3）
enum CarryOverPolicy {
  /// その日限りで消える。翌日のカードには現れない（過去のカードには残る）。
  none,

  /// 未完了なら翌日のカードにも繰り越して表示する。
  carryOver,
}

/// 繰り返し予定を編集・削除したときの適用範囲。（レビュー追加提起）
enum RepeatEditScope {
  /// その日の分だけに適用する。
  thisDayOnly,

  /// 今後すべての回に適用する。
  allFuture,
}

/// 音声認識をどこで処理するか。（レビュー追加提起 No.10）
enum SpeechRecognitionMode {
  /// OS 既定に任せる。多くの場合ネットワーク経由となり精度が高い。
  /// プライバシーポリシーに「文字起こしのため OS の音声認識機能を利用する」
  /// 旨の記載が必須になる。
  preferAccuracy,

  /// 端末内処理を強制する。外部送信は発生しないが、対応端末が限られ
  /// 日本語の精度も落ちる。
  forceOnDevice,
}

/// アプリ全体の設定既定値。
class AppConfig {
  const AppConfig._();

  // ---------------------------------------------------------------------------
  // カードの上限（要件定義書 第2.0版 2.2）
  // ---------------------------------------------------------------------------

  /// 1日あたりに登録できる予定の上限。
  ///
  /// 人が一度に覚えやすいのは 4±1 項目、という考え方に基づく。（要件定義書 2.2）
  /// 6件目を登録しようとした場合は穏やかな案内を出し、その日への追加は
  /// 控えていただく（別日への登録は妨げない）。
  ///
  /// 将来フェーズ2で上限を変更する可能性があるため、値はこの1箇所だけで
  /// 定義する。画面側にも判定ロジックにも数値を直接書かないこと。
  static const maxSchedulesPerDay = 5;

  // ---------------------------------------------------------------------------
  // 確定した仕様（要件定義書 第2.0版 11.1）
  // ---------------------------------------------------------------------------

  /// 確認事項 No.3：完了しなかった予定の繰り越し。
  ///
  /// **確定**：その日限り（翌日へ繰り越さない）。
  /// コンセプトが「今日はこれだけ覚えておけば大丈夫」である以上、
  /// 未完了分が積み上がって見える状態は「思い出せる安心」ではなく
  /// 「できていない不安」を与えるため。
  static const carryOverPolicy = CarryOverPolicy.none;

  /// レビュー追加提起 No.13：繰り返し予定の編集・削除の適用範囲。
  ///
  /// 暫定 [RepeatEditScope.allFuture]。対象利用者に対して
  /// 「この日だけ／今後すべて」の選択肢を出すこと自体が負荷になるため、
  /// MVP では選択させずに今後すべてへ適用する。
  static const repeatEditScope = RepeatEditScope.allFuture;

  /// レビュー追加提起 No.10：音声認識の処理場所。
  ///
  /// 暫定 [SpeechRecognitionMode.preferAccuracy]。認識精度が体験の質を
  /// 直接左右するため。プライバシーポリシーの記載と対で確定させること。
  static const speechRecognitionMode = SpeechRecognitionMode.preferAccuracy;

  /// レビュー追加提起 No.12：予定が0件の日も通知を出すか。
  ///
  /// **確定** true。通知が来ない日があると「壊れたのでは」という不安に
  /// つながるため、必ず届ける。予定がある日と同じ文面を使う。
  /// （お客様ご指摘 2026/08/17：予定ありの場合も予定なしの場合も同じ挨拶）
  static const notifyOnEmptyDays = true;

  /// 確認事項 No.5：カレンダーで遡れる範囲。
  ///
  /// 暫定：全期間。端末内保存のみでデータ量も小さいため制限しない。
  static const int? calendarPastLimitDays = null;
  static const int? calendarFutureLimitDays = null;

  // ---------------------------------------------------------------------------
  // 通知
  // ---------------------------------------------------------------------------

  /// 就寝時刻の既定値。初回設定で伺えなかった場合のフォールバック。
  static const defaultSleepTime = ClockTime(22, 0);

  /// 起床時刻の既定値。
  static const defaultWakeTime = ClockTime(7, 0);

  /// 就寝の何分前に前日夜の通知を出すか。（要件定義書 6.2）
  static const notificationOffsetBeforeSleep = Duration(minutes: 30);

  /// 起床の何分前に当日朝の通知を出すか。（要件定義書 6.2）
  static const notificationOffsetBeforeWake = Duration(minutes: 30);

  /// 通知を何日先まで事前に予約しておくか。
  ///
  /// ローカル通知は予約時点で内容が固定される。タップして開くカードの日付を
  /// 通知ごとに持たせる必要があるため、日ごとに予約する。iOS の保留通知上限は
  /// 64件、1日2件なので 14日 × 2 = 28件で収まる。
  static const notificationScheduleHorizonDays = 14;

  // ---------------------------------------------------------------------------
  // カードの表示バリアント判定
  // ---------------------------------------------------------------------------

  /// レビュー追加提起 No.14：カード表示パターンの時間境界。
  ///
  /// 設定済みの2つの通知時刻をそのまま境界として使う。利用者が通知時刻を
  /// 変更するとカードの表情も連動するため、体験が一貫する。
  ///
  /// - 朝通知時刻 〜 正午          → 当日朝
  /// - 正午 〜 翌朝の通知時刻      → 当日日中
  /// - 夜通知時刻 〜 翌0時         → 当日のカードは日中のまま。
  ///                                 主役は「明日のカード」に移る
  ///
  /// 一日を締める専用の表示（当日夜）は持たない。夜の通知から開くのは
  /// 明日のカードであり、当日のカードを別の表情に切り替えると二重になる。
  /// （お客様ご指摘 2026/08/17）
  static const middayBoundaryHour = 12;

  // ---------------------------------------------------------------------------
  // 音声入力
  // ---------------------------------------------------------------------------

  /// 無音がこの時間続いたら録音を自動停止する。（要件定義書 4.2）
  ///
  /// OS 既定値は対象利用者には短すぎる。ゆっくり話す人・言い淀む人の途中で
  /// 切れる事故を避けるため長めに取り、あわせて明示的な停止ボタンも併置する。
  static const speechPauseFor = Duration(seconds: 4);

  /// 1回の録音の最大長。
  static const speechListenFor = Duration(seconds: 60);

  /// 音声認識の言語。
  static const speechLocaleId = 'ja_JP';

  // ---------------------------------------------------------------------------
  // 予定解析
  // ---------------------------------------------------------------------------

  /// 要件定義書 5章の表に無い言い方のうち、実装コストが小さく
  /// 失敗を減らす効果が大きいものを有効化するか。
  ///
  /// 具体的には「明後日」「今週の◯曜」「来月◯日」。
  /// 契約上のスコープは5章の表までであり、これらは精度保証の対象外とする。
  static const enableParserExtensions = true;

  /// 「毎朝」「毎晩」に既定の時刻を割り当てるか。
  ///
  /// 暫定 false（終日扱い）。「毎朝」を起床時刻に紐づけると、利用者が
  /// 起床時刻を変えたときに過去の予定の時刻まで動いてしまうため。
  static const assignDefaultTimeToMorningNight = false;
}
